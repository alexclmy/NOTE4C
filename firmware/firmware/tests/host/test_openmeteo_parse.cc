// ------------------------------------------------------------- the cache --

static void test_a_forecast_survives_the_cache_encoding() {
    Forecast f;
    CHECK(Parse(BuildResponse(Build{}), &f));

    uint8_t buf[kEncodedForecastBytes];
    const size_t n = EncodeForecast(f, buf, sizeof(buf));
    CHECK_EQ_INT(n, kEncodedForecastBytes);

    Forecast back;
    CHECK(DecodeForecast(buf, n, &back));
    CHECK_EQ_INT(back.fetched_epoch, f.fetched_epoch);
    CHECK_EQ_INT(back.first_hour_epoch, f.first_hour_epoch);
    CHECK_EQ_INT(back.hour_count, f.hour_count);
    CHECK_EQ_INT(back.low_c10, f.low_c10);
    CHECK_EQ_INT(back.high_c10, f.high_c10);
    CHECK(memcmp(back.temp_c10, f.temp_c10, sizeof(f.temp_c10)) == 0);
    CHECK(memcmp(back.wmo, f.wmo, sizeof(f.wmo)) == 0);
}

static void test_negative_temperatures_survive_the_encoding() {
    // Sign matters and the encoding is hand-rolled, so a January forecast is
    // worth one test of its own.
    Forecast f;
    f.hour_count = kMaxHours;
    for (size_t i = 0; i < kMaxHours; ++i) f.temp_c10[i] = static_cast<int16_t>(-200 - i);
    f.low_c10 = -223;
    f.high_c10 = -200;
    uint8_t buf[kEncodedForecastBytes];
    CHECK_EQ_INT(EncodeForecast(f, buf, sizeof(buf)), kEncodedForecastBytes);
    Forecast back;
    CHECK(DecodeForecast(buf, sizeof(buf), &back));
    CHECK_EQ_INT(back.low_c10, -223);
    CHECK_EQ_INT(back.high_c10, -200);
    CHECK_EQ_INT(back.temp_c10[23], -223);
}

static void test_the_cache_record_fits_its_slot_budget() {
    // The plan budgets 4 KB for this record; the encoding is under 100 bytes.
    CHECK(kEncodedForecastBytes <= 4096);
}

static void test_a_corrupt_cache_record_is_refused() {
    Forecast f;
    CHECK(Parse(BuildResponse(Build{}), &f));
    uint8_t buf[kEncodedForecastBytes];
    CHECK(EncodeForecast(f, buf, sizeof(buf)) > 0);

    Forecast back;
    buf[0] = 'X';
    CHECK(!DecodeForecast(buf, sizeof(buf), &back));
    buf[0] = 'W';
    buf[3] = 99;  // a version this build does not know
    CHECK(!DecodeForecast(buf, sizeof(buf), &back));
    buf[3] = 1;
    CHECK(!DecodeForecast(buf, sizeof(buf) - 1, &back));  // truncated
}

static void test_encoding_refuses_a_buffer_that_is_too_small() {
    Forecast f;
    uint8_t buf[8];
    CHECK_EQ_INT(EncodeForecast(f, buf, sizeof(buf)), 0);
}

