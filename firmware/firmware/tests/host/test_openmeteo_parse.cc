// --------------------------------------------------------------- the stamp --

static void test_iso_stamps_become_utc_epochs() {
    int64_t epoch = 0;
    CHECK(ParseIso8601Utc("2026-09-14T12:00", 16, &epoch));
    CHECK_EQ_INT(epoch, kNow);
    CHECK(ParseIso8601Utc("2026-09-14T12:00:00", 19, &epoch));
    CHECK_EQ_INT(epoch, kNow);
    CHECK(ParseIso8601Utc("2026-09-14T12:00:00Z", 20, &epoch));
    CHECK_EQ_INT(epoch, kNow);
    CHECK(ParseIso8601Utc("1970-01-01T00:00", 16, &epoch));
    CHECK_EQ_INT(epoch, 0);
}

static void test_leap_days_are_real_and_non_leap_days_are_not() {
    int64_t epoch = 0;
    CHECK(ParseIso8601Utc("2024-02-29T00:00", 16, &epoch));
    CHECK(!ParseIso8601Utc("2023-02-29T00:00", 16, &epoch));
    // 2000 is a leap year, 1900 is not. A date routine that gets this wrong is
    // wrong one day in four years, which is not a thing anybody finds by
    // looking at it.
    CHECK(ParseIso8601Utc("2000-02-29T00:00", 16, &epoch));
    CHECK(!ParseIso8601Utc("1900-02-29T00:00", 16, &epoch));
}

static void test_a_stamp_with_an_offset_is_refused_not_shifted() {
    int64_t epoch = 0;
    // The request pins timezone=UTC. A reply carrying +02:00 means the service
    // ignored that, and guessing which way to shift moves an hour of weather.
    CHECK(!ParseIso8601Utc("2026-09-14T12:00+02:00", 22, &epoch));
    CHECK(!ParseIso8601Utc("2026-09-14T12:00-05:00", 22, &epoch));
}

static void test_malformed_stamps_are_refused() {
    int64_t epoch = 0;
    CHECK(!ParseIso8601Utc("2026-09-14", 10, &epoch));
    CHECK(!ParseIso8601Utc("2026/09/14T12:00", 16, &epoch));
    CHECK(!ParseIso8601Utc("20xx-09-14T12:00", 16, &epoch));
    CHECK(!ParseIso8601Utc("2026-13-01T12:00", 16, &epoch));
    CHECK(!ParseIso8601Utc("2026-09-31T12:00", 16, &epoch));
    CHECK(!ParseIso8601Utc("2026-09-14T25:00", 16, &epoch));
    CHECK(!ParseIso8601Utc("2026-09-14T12:61", 16, &epoch));
    CHECK(!ParseIso8601Utc("", 0, &epoch));
}

// ------------------------------------------------------------- the contract --

static void test_a_complete_forecast_is_accepted() {
    Forecast f;
    CHECK(Parse(BuildResponse(Build{}), &f));
    CHECK(f.valid());
    CHECK_EQ_INT(f.hour_count, 24);
    CHECK_EQ_INT(f.first_hour_epoch, kNow);
    CHECK_EQ_INT(f.fetched_epoch, kNow);
    // Temperatures cycle 10.0..16.0, so the bounds are exact rather than
    // approximately right.
    CHECK_EQ_INT(f.low_c10, 100);
    CHECK_EQ_INT(f.high_c10, 160);
}

static void test_hours_outside_the_window_are_dropped() {
    // The response carries three days; only the next 24 hours are kept.
    Build b;
    b.hours = 72;
    Forecast f;
    CHECK(Parse(BuildResponse(b), &f));
    CHECK_EQ_INT(f.hour_count, 24);
}

static void test_exactly_23_hours_is_enough() {
    // The floor of the contract: 23 entries, first within the hour, last at
    // 23 hours out.
    Build b;
    b.hours = 24;
    b.skip_index = 5;
    Forecast f;
    ParseError err;
    const bool ok = Parse(BuildResponse(b), &f, &err);
    // Skipping one entry makes a two-hour gap, which the contract refuses even
    // though the count is still 23. Both rules matter, and this pins that.
    CHECK(!ok);
    CHECK(err.code == kErrCoverage);
}

static void test_a_forecast_that_starts_too_late_is_refused() {
    Build b;
    b.start_offset = 2 * 3600;  // first entry two hours away
    ExpectRefusal(BuildResponse(b), kErrCoverage);
}

static void test_a_forecast_that_stops_short_is_refused() {
    Build b;
    b.hours = 12;  // only half a day
    ExpectRefusal(BuildResponse(b), kErrCoverage);
}

static void test_a_gap_wider_than_an_hour_is_refused() {
    Build b;
    b.hours = 30;
    b.skip_index = 10;
    ExpectRefusal(BuildResponse(b), kErrCoverage);
}

static void test_a_null_temperature_makes_a_gap_and_is_refused() {
    // The tower drops null-temperature hours; dropping one mid-window leaves a
    // two-hour gap, and a panel drawn from it would interpolate weather that
    // was never forecast.
    Build b;
    b.hours = 30;
    b.null_temp_index = 8;
    ExpectRefusal(BuildResponse(b), kErrCoverage);
}

static void test_a_null_weather_code_is_tolerated_as_unknown() {
    // A missing code costs one icon, not the forecast. The temperature is the
    // number on the panel; the sky is decoration around it.
    Build b;
    b.null_code_index = 3;
    Forecast f;
    CHECK(Parse(BuildResponse(b), &f));
    CHECK_EQ_INT(f.wmo[3], 255);
    CHECK(ConditionForWmoCode(255) == Condition::kUnknown);
}

static void test_arrays_of_different_lengths_are_refused() {
    Build b;
    b.short_temps = true;
    ExpectRefusal(BuildResponse(b), kErrLengths);
}

static void test_fahrenheit_is_refused_not_converted() {
    // The device asks for Celsius. A reply in anything else means the device
    // and the service are not talking about the same thing, and a converter
    // here would hide exactly the change worth seeing.
    Build b;
    b.unit = "\xc2\xb0""F";
    ExpectRefusal(BuildResponse(b), kErrUnits);
}

static void test_celsius_is_accepted_in_both_spellings() {
    for (const char* unit : {"\xc2\xb0""C", "C"}) {
        Build b;
        b.unit = unit;
        Forecast f;
        CHECK(Parse(BuildResponse(b), &f));
    }
}

static void test_a_response_with_no_units_block_is_accepted() {
    // The request pins the default, so an absent block is not a disagreement.
    Build b;
    b.include_units = false;
    Forecast f;
    CHECK(Parse(BuildResponse(b), &f));
}

static void test_an_implausible_temperature_is_refused() {
    Build b;
    b.temp_override_index = 4;
    b.temp_override = 500.0;  // not a temperature this planet has
    ExpectRefusal(BuildResponse(b), kErrTemperature);

    Build cold = Build{};
    cold.temp_override_index = 4;
    cold.temp_override = -200.0;
    ExpectRefusal(BuildResponse(cold), kErrTemperature);
}

static void test_a_temperature_at_the_edge_of_plausible_is_accepted() {
    Build b;
    b.temp_override_index = 4;
    b.temp_override = 59.9;
    Forecast f;
    CHECK(Parse(BuildResponse(b), &f));
    CHECK_EQ_INT(f.high_c10, 599);
}

static void test_a_duplicate_hourly_key_is_refused() {
    std::string doc = BuildResponse(Build{});
    const size_t at = doc.find("\"hourly\":");
    doc.insert(at, "\"hourly\":{\"time\":[],\"temperature_2m\":[],\"weather_code\":[]},");
    ExpectRefusal(doc, kErrDuplicate);
}

static void test_unknown_root_and_hourly_fields_are_skipped() {
    // The opposite of the profile's rule, deliberately: this is a third-party
    // response that may legitimately grow fields, and refusing those would mean
    // the panel goes dark the day Open-Meteo adds one.
    std::string doc = BuildResponse(Build{});
    const size_t at = doc.find("\"hourly\":{");
    doc.insert(at, "\"daily\":{\"sunrise\":[\"x\"]},\"new_field\":[1,2,3],");
    const size_t inner = doc.rfind("\"time\":");
    doc.insert(inner, "\"apparent_temperature\":[1,2],");
    Forecast f;
    CHECK(Parse(doc, &f));
    CHECK(f.valid());
}

// --------------------------------------------------------- the bad documents --

static void test_html_is_refused() {
    // A captive portal or an error page, which is what a device on a hotel
    // network actually receives.
    ExpectRefusal("<!DOCTYPE html><html><body>Not found</body></html>", kErrShape);
}

static void test_an_empty_body_is_refused() {
    ExpectRefusal("", kErrShape);
}

static void test_a_json_error_object_is_refused() {
    ExpectRefusal(R"({"error":true,"reason":"Cannot initialize WeatherVariable"})",
                  kErrShape);
}

static void test_every_truncation_of_a_good_response_is_refused() {
    // A connection that dropped part way through is the common failure, and a
    // truncated JSON array must never read as a shorter forecast. Under ASan
    // this also proves nothing reads off the end.
    const std::string full = BuildResponse(Build{});
    for (size_t cut = 0; cut < full.size(); cut += 7) {
        Forecast f;
        ParseError err;
        if (ParseForecast(full.data(), cut, kNow, &f, &err)) {
            ++g_failures;
            printf("  FAIL in %s: prefix of %zu bytes was accepted\n", g_current, cut);
        }
        ++g_checks;
    }
    Forecast whole;
    CHECK(Parse(full, &whole));
}

static void test_a_body_past_the_size_bound_is_refused_before_parsing() {
    const std::string huge(kMaxResponseBytes + 1, ' ');
    ExpectRefusal(huge, kErrTooLarge);
}

static void test_a_trailing_comma_is_refused() {
    std::string doc = BuildResponse(Build{});
    const size_t at = doc.rfind("]}}");
    doc.insert(at, ",");
    ExpectRefusal(doc, kErrShape);
}

